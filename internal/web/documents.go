const (
	maxFileName = 200
	// multipartSlack covers the multipart framing around the file itself.
	multipartSlack = 64 << 10

	// docCSP confines a rendered document to an opaque origin: no cookie, no same-origin access to
	// the API, no network but this server's static files. The sandbox directive also holds when
	// the URL is opened directly rather than in the room's iframe.
	docCSP = "sandbox allow-scripts; default-src 'none'; script-src 'self' 'unsafe-inline'; " +
		"style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; " +
		"base-uri 'none'; form-action 'none'; frame-ancestors 'self'"
	// originalCSP serves originals inert, an SVG opened on its own included.
	originalCSP = "sandbox; default-src 'none'; img-src 'self' data:; style-src 'unsafe-inline'; frame-ancestors 'self'"
	// pdfCSP: Chrome refuses to run its PDF viewer in a sandboxed document.
	pdfCSP = "default-src 'none'; frame-ancestors 'self'"
)

// uploadReadTimeout bounds reading one upload body: the server has no ReadTimeout, which would cut
// event streams. A var for tests.
var uploadReadTimeout = 2 * time.Minute

// Options configures documents and uploads.
type Options struct {
	MaxUploadBytes int64
	// MaxRoomBytes is the default room quota; the super-admin sets others room by room (004-AC9).
	MaxRoomBytes int64
	// MaxAttachmentBytes bounds one image on an annotation message.
	MaxAttachmentBytes int64
	// ToMarkdown converts an office file read as the pandoc format from.
	ToMarkdown func(ctx context.Context, from string, data []byte) (string, error)
	// Voice turns on LiveKit audio and transcription; nil leaves the room text only.
	Voice *Voice
	// TTSTokenHash is HashToken of the tts pod's token: set with Voice, personas speak in the call
	// (013-AC13); empty, every /api/tts route answers 404.
	TTSTokenHash string
	// TurnTimeout bounds one agent turn; 0 means 15 minutes.
	TurnTimeout time.Duration
	// NotesWatchDelay is how long the notes watcher waits after the last new note message; 0 means
	// DefaultNotesWatchDelay (009-AC32).
	NotesWatchDelay time.Duration
	// MaxResultBytes bounds a turn result a daemon posts; 0 means 32 MB.
	MaxResultBytes int64
	// Release is the daemon release handed out to hosts; nil offers no download.
	Release *Release
	// PrevRelease is the release before it, handed out to supervisors whose protocol window the
	// current one's workers fall outside; nil keeps none.
	PrevRelease *Release
	// SandboxImage is the digest-pinned sandbox image daemons pull; empty lets them build their own.
	SandboxImage string
	// SendMail mails a plain-text message; nil turns email sign-in off.
	SendMail func(ctx context.Context, to, subject, body string) error
	// MagicLinkTTL is how long an emailed link works; 0 means 15 minutes.
	MagicLinkTTL time.Duration
	// AuditRetention is how long the audit log keeps an entry; 0 means DefaultAuditRetention.
	AuditRetention time.Duration
	// ClientRetention is how long a participant's IP and user agent are kept; 0 means
	// DefaultClientRetention (005-AC20).
	ClientRetention time.Duration
	// TrustedProxies are the peers whose X-Forwarded-For names the client (005-AC20).
	TrustedProxies []netip.Prefix
	// PushHosts are the push services a Web Push subscription may name, by host suffix; nil means
	// DefaultPushHosts (005-AC24). PushClient posts to them; nil means one with a timeout and no
	// redirect.
	PushHosts  []string
	PushClient *http.Client
	// PluginClient fetches plugins from git; nil means plugin.NewClient(), which reaches public
	// https addresses only (009-AC8). Tests pass one that reaches their local git server.
	PluginClient *http.Client
	// MaxImportBytes bounds an imported archive, compressed and once uncompressed; 0 means
	// DefaultMaxImportBytes.
	MaxImportBytes int64
	// Version is the server's own, and DBPath its database file: the instance view shows both, and
	// exports and imports stage beside the database.
	Version string
	DBPath  string
	// DeviceSTTDir holds the device transcription files; empty, or incomplete at start, offers no
	// device mode (010-AC5). DeviceSTTManifest is what it must hold; nil means devicestt.Pinned.
	DeviceSTTDir      string
	DeviceSTTManifest *devicestt.Manifest
}

