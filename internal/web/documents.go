func sizeText(n int64) string {
	if n%(1<<20) == 0 {
		return fmt.Sprintf("%d MB", n>>20)
	}
	return fmt.Sprintf("%d bytes", n)
}

func (s *Server) listDocuments(w http.ResponseWriter, r *http.Request, sess session) {
	docs, err := s.bus.Store.Documents(r.Context(), sess.p.RoomID)
	if err != nil {
		s.serverError(w, "list_documents_failed", err)
		return
	}
	writeJSON(w, http.StatusOK, docs)
}

// document loads the {doc} of the session's room, or answers 404.
func (s *Server) document(w http.ResponseWriter, r *http.Request, sess session) (*store.Document, bool) {
	id, err := strconv.ParseInt(r.PathValue("doc"), 10, 64)
	if err != nil {
		httpError(w, http.StatusNotFound, "no such document")
		return nil, false
	}
	d, err := s.bus.Store.Document(r.Context(), sess.p.RoomID, id)
	if errors.Is(err, store.ErrNotFound) {
		httpError(w, http.StatusNotFound, "no such document")
		return nil, false
	}
	if err != nil {
		s.serverError(w, "get_document_failed", err)
		return nil, false
	}
	return d, true
}

type documentResp struct {
	Document  *store.Document  `json:"document"`
	Revisions []store.Revision `json:"revisions"`
}

func (s *Server) getDocument(w http.ResponseWriter, r *http.Request, sess session) {
	d, ok := s.document(w, r, sess)
	if !ok {
		return
	}
	revs, err := s.bus.Store.Revisions(r.Context(), d.ID)
	if err != nil {
		s.serverError(w, "get_document_failed", err)
		return
	}
	writeJSON(w, http.StatusOK, documentResp{Document: d, Revisions: revs})
}

// readUpload returns the name and bytes of the "file" part, or answers the error itself.
func (s *Server) readUpload(w http.ResponseWriter, r *http.Request) (string, []byte, bool) {
	mt, params, _ := mime.ParseMediaType(r.Header.Get("Content-Type"))
	if mt != "multipart/form-data" || params["boundary"] == "" {
		httpError(w, http.StatusUnsupportedMediaType, "Content-Type must be multipart/form-data")
		return "", nil, false
	}
	tooLarge := fmt.Sprintf("file is over the %s limit", sizeText(s.opts.MaxUploadBytes))
	mr := multipart.NewReader(http.MaxBytesReader(w, r.Body, s.opts.MaxUploadBytes+multipartSlack), params["boundary"])
	for {
		part, err := mr.NextPart()
		var mbe *http.MaxBytesError
		switch {
		case errors.As(err, &mbe):
			httpError(w, http.StatusRequestEntityTooLarge, tooLarge)
			return "", nil, false
		case errors.Is(err, io.EOF):
			httpError(w, http.StatusBadRequest, "missing file field")
			return "", nil, false
		case err != nil:
			httpError(w, http.StatusBadRequest, "bad multipart body")
			return "", nil, false
		}
		if part.FormName() != "file" {
			continue
		}
		// FileName keeps only the base name, so no path reaches the store.
		name, ok := cleanText(part.FileName(), maxFileName, false)
		if !ok {
			httpError(w, http.StatusBadRequest, fmt.Sprintf("file name must be 1 to %d characters", maxFileName))
			return "", nil, false
		}
		data, err := io.ReadAll(io.LimitReader(part, s.opts.MaxUploadBytes+1))
		if errors.As(err, &mbe) || int64(len(data)) > s.opts.MaxUploadBytes {
			httpError(w, http.StatusRequestEntityTooLarge, tooLarge)
			return "", nil, false
		}
		if err != nil {
			httpError(w, http.StatusBadRequest, "bad multipart body")
			return "", nil, false
		}
		if len(data) == 0 {
			httpError(w, http.StatusBadRequest, "empty file")
			return "", nil, false
		}
		return name, data, true
	}
}

// roomFull answers an upload or attachment refused by the room's quota (004-AC9).
func (s *Server) roomFull(w http.ResponseWriter, r *http.Request, room string) {
	_, quota, err := s.bus.Store.RoomUsage(r.Context(), room, s.opts.MaxRoomBytes)
	if err != nil {
		s.serverError(w, "room_usage_failed", err)
		return
	}
	httpError(w, http.StatusRequestEntityTooLarge, fmt.Sprintf("this upload would take the room over its %s limit", sizeText(quota)))
}

func (s *Server) uploadDocument(w http.ResponseWriter, r *http.Request, sess session) {
	// Each upload holds its body, a text copy and pandoc's output in memory.
	select {
	case s.uploads <- struct{}{}:
		defer func() { <-s.uploads }()
	default:
		httpError(w, http.StatusServiceUnavailable, "too many uploads in progress, retry in a moment")
		return
	}
	if err := http.NewResponseController(w).SetReadDeadline(time.Now().Add(uploadReadTimeout)); err != nil {
		s.serverError(w, "upload_deadline_failed", err)
		return
	}
	name, data, ok := s.readUpload(w, r)
	if !ok {
		return
	}
	typ, err := convert.Detect(name, data)
	if err != nil {
		httpError(w, http.StatusUnsupportedMediaType, err.Error())
		return
	}
	// Early answer for a full room, before pandoc spends its time; AddUpload re-checks atomically.
	used, quota, err := s.bus.Store.RoomUsage(r.Context(), sess.p.RoomID, s.opts.MaxRoomBytes)
	if err != nil {
		s.serverError(w, "upload_failed", err)
		return
	}
	if used+int64(len(data)) > quota {
		s.roomFull(w, r, sess.p.RoomID)
		return
	}
	text := ""
	switch {
	case typ.Reader != "":
		text, err = s.opts.ToMarkdown(r.Context(), typ.Reader, data)
		if errors.Is(err, exec.ErrNotFound) || errors.Is(err, fs.ErrNotExist) {
			s.log.Error("pandoc_missing", zap.Error(err))
			httpError(w, http.StatusServiceUnavailable, "document conversion is unavailable on this server")
			return
		}
		if err != nil {
			s.log.Warn("upload_conversion_failed", zap.String("room", sess.p.RoomID), zap.String("reader", typ.Reader), zap.Error(err))
			httpError(w, http.StatusUnprocessableEntity, "could not convert "+name+" to Markdown")
			return
		}
	case typ.Format == convert.FormatMD || typ.Format == convert.FormatHTML:
		text = string(data)
	}
	d, err := s.bus.Store.AddUpload(r.Context(), &store.Upload{
		RoomID: sess.p.RoomID, ParticipantID: sess.p.ID, Author: sess.p.Name, Filename: name,
		ContentType: typ.ContentType, Format: typ.Format, Data: data, Text: text,
	}, s.opts.MaxRoomBytes)
	if errors.Is(err, store.ErrRoomFull) {
		s.roomFull(w, r, sess.p.RoomID)
		return
	}
	if err != nil {
		s.serverError(w, "upload_failed", err)
		return
	}
	s.bus.Notify(d.RoomID)
	s.log.Info("document_uploaded", zap.String("room", d.RoomID), zap.Int64("document", d.ID),
		zap.String("content_type", d.ContentType), zap.Int64("size", d.Size))
	writeJSON(w, http.StatusCreated, d)
}

// revisionParam reads a revision number from the query; def when absent.
func revisionParam(r *http.Request, key string, def int) (int, bool) {
	v := r.URL.Query().Get(key)
	if v == "" {
		return def, true
	}
	n, err := strconv.Atoi(v)
	return n, err == nil
}

// viewDocument serves revision ?rev= (default latest) of a text document as a page for the
// sandboxed iframe; with ?from=, the word-level diff from that revision to it.
func (s *Server) viewDocument(w http.ResponseWriter, r *http.Request, sess session) {
	d, ok := s.document(w, r, sess)
	if !ok {
		return
	}
	if d.Revisions == 0 {
		httpError(w, http.StatusNotFound, "this document has no text view")
		return
	}
	n, ok1 := revisionParam(r, "rev", d.Revisions)
	from, ok2 := revisionParam(r, "from", 0)
	if !ok1 || !ok2 {
		httpError(w, http.StatusBadRequest, "rev and from must be revision numbers")
		return
	}
	body, err := s.revisionHTML(r.Context(), d, n)
	if errors.Is(err, store.ErrNotFound) {
		httpError(w, http.StatusNotFound, "no such revision")
		return
	}
	if err != nil {
		s.serverError(w, "view_document_failed", err)
		return
	}
	if from != 0 {
		old, err := s.revisionHTML(r.Context(), d, from)
		if errors.Is(err, store.ErrNotFound) {
			httpError(w, http.StatusNotFound, "no such revision")
			return
		}
		if err != nil {
			s.serverError(w, "view_document_failed", err)
			return
		}
		body = render.DiffHTML(old, body)
	}
	var page bytes.Buffer
	if d.Format == convert.FormatHTML {
		tags := annotateScript
		if from != 0 {
			tags = append(append([]byte{}, diffStyle...), annotateScript...)
		}
		page.Write(inHead(body, tags))
	} else {
		err = docTmpl.Execute(&page, map[string]any{
			"Title":     d.Name,
			"Content":   template.HTML(body), //nolint:gosec // the document is untrusted by design: docCSP sandboxes it
			"CodeLight": codeLight,
			"CodeDark":  codeDark,
			"Math":      bytes.Contains(body, []byte(`class="math `)),
			"Mermaid":   bytes.Contains(body, []byte(`class="mermaid"`)),
			"Width":     mdWidth(r.URL.Query().Get("width")),
		})
		if err != nil {
			s.serverError(w, "view_document_failed", err)
			return
		}
	}
	h := w.Header()
	h.Set("Content-Security-Policy", docCSP)
	// Firefox checks the sandboxed frame's navigation as cross-origin under the room page's COEP and
	// refuses it without this; same-origin and same-site fail there. The cookies are SameSite=Strict.
	h.Set("Cross-Origin-Resource-Policy", "cross-origin")
	h.Set("Content-Type", "text/html; charset=utf-8")
	h.Set("Cache-Control", "no-store")
	_, _ = w.Write(page.Bytes())
}

// mdWidth is the Markdown text width a view asks for (008-AC7): large or full, else the default
// narrow one, which needs no attribute.
func mdWidth(v string) string {
	if v == "large" || v == "full" {
		return v
	}
	return ""
}

// revisionHTML returns revision n of d as HTML: rendered for Markdown, as is for HTML.
func (s *Server) revisionHTML(ctx context.Context, d *store.Document, n int) ([]byte, error) {
	rev, err := s.bus.Store.Revision(ctx, d.ID, n)
	if err != nil {
		return nil, err
	}
	if d.Format == convert.FormatHTML {
		return []byte(rev.Body), nil
	}
	return render.MdToHTML([]byte(rev.Body))
}

var (
	diffStyle = []byte(`<link rel="stylesheet" href="/static/doc/github-diff.css">`)
	// annotateScript draws annotation marks inside the frame; the template carries it for Markdown.
	annotateScript = []byte(`<link rel="stylesheet" href="/static/doc/annotate.css"><script src="/static/doc/annotate.js"></script>`)
	// headTag is the <head> start tag, not <header>.
	headTag = regexp.MustCompile(`(?i)<head(\s[^>]*)?>`)
	// leadingDoctype is a doctype with only blanks and comments before it.
	leadingDoctype = regexp.MustCompile(`(?is)^(?:\s|<!--.*?-->)*<!doctype[^>]*>`)
)

// inHead inserts tags into an HTML document's head: after its <head> tag, else after its
// doctype, else at the start. Before a doctype they would switch the page to quirks mode.
func inHead(page, tags []byte) []byte {
	at := 0
	if m := headTag.FindIndex(page); m != nil {
		at = m[1]
	} else if m := leadingDoctype.FindIndex(page); m != nil {
		at = m[1]
	}
	return append(append(append([]byte{}, page[:at]...), tags...), page[at:]...)
}

// originalDocument serves an upload's original bytes: inline for PDF and images, as a download
// otherwise.
func (s *Server) originalDocument(w http.ResponseWriter, r *http.Request, sess session) {
	d, ok := s.document(w, r, sess)
	if !ok {
		return
	}
	data, err := s.bus.Store.Original(r.Context(), d.RoomID, d.ID)
	if errors.Is(err, store.ErrNotFound) {
		httpError(w, http.StatusNotFound, "this document has no original")
		return
	}
	if err != nil {
		s.serverError(w, "original_document_failed", err)
		return
	}
	h := w.Header()
	disposition, csp := "attachment", originalCSP
	switch d.Format {
	case convert.FormatPDF:
		disposition, csp = "inline", pdfCSP
	case convert.FormatImage:
		disposition = "inline"
	}
	h.Set("Content-Security-Policy", csp)
	// Only the room page loads it, never the sandboxed frame: no other origin needs it.
	h.Set("Cross-Origin-Resource-Policy", "same-origin")
	h.Set("Content-Type", d.ContentType)
	h.Set("Content-Disposition", mime.FormatMediaType(disposition, map[string]string{"filename": d.Name}))
	h.Set("Content-Length", strconv.Itoa(len(data)))
	_, _ = w.Write(data)
}

// renameDocument renames a document for any member (005-AC25): the name passes the checks an
// upload's does, an agent document's those of its workspace path too, and keeps its extension.
func (s *Server) renameDocument(w http.ResponseWriter, r *http.Request, sess session) {
	var req struct {
		Name string `json:"name"`
	}
	if !decode(w, r, &req) {
		return
	}
	d, ok := s.document(w, r, sess)
	if !ok {
		return
	}
	name, ok := cleanText(req.Name, maxFileName, false)
	switch {
	case !ok || strings.ContainsAny(name, `/\`):
		httpError(w, http.StatusBadRequest, fmt.Sprintf("file name must be 1 to %d characters, without / or \\", maxFileName))
		return
	case !strings.EqualFold(path.Ext(name), path.Ext(d.Name)):
		httpError(w, http.StatusBadRequest, "the name must keep the extension "+path.Ext(d.Name))
		return
	case d.Kind == store.DocAgent && !turn.ValidDocName(name):
		httpError(w, http.StatusBadRequest, "not a name an agent document can take")
		return
	}
	c, err := s.bus.Store.RenameDocument(r.Context(), sess.p.RoomID, d.ID, name, sess.p)
	if s.docChangeFailed(w, err, "rename_document_failed") {
		return
	}
	if c != nil {
		s.bus.Notify(sess.p.RoomID)
		s.log.Info("document_renamed", zap.String("room", sess.p.RoomID), zap.Int64("document", d.ID), zap.Int64("participant", sess.p.ID))
	}
	w.WriteHeader(http.StatusNoContent)
}

// docChangeFailed answers a refused document change and reports whether it did.
func (s *Server) docChangeFailed(w http.ResponseWriter, err error, event string) bool {
	switch {
	case err == nil:
		return false
	case errors.Is(err, store.ErrNotFound):
		httpError(w, http.StatusNotFound, "no such document")
	case errors.Is(err, store.ErrForbidden):
		httpError(w, http.StatusForbidden, "only a room admin can do this")
	case errors.Is(err, store.ErrDocNameTaken), errors.Is(err, store.ErrTurnRunning):
		httpError(w, http.StatusConflict, err.Error())
	default:
		s.serverError(w, event, err)
	}
	return true
}

// setDocumentDeleted deletes a document softly (DELETE), or restores it (POST .../restore), for a
// room admin or the super-admin (005-AC26), audited.
func (s *Server) setDocumentDeleted(w http.ResponseWriter, r *http.Request, sess *session) {
	if !s.asRoomAdmin(w, r, sess) {
		return
	}
	id, err := strconv.ParseInt(r.PathValue("doc"), 10, 64)
	if err != nil {
		httpError(w, http.StatusNotFound, "no such document")
		return
	}
	deleted, action := r.Method == http.MethodDelete, ActionDocumentDelete
	if !deleted {
		action = ActionDocumentRestore
	}
	room := r.PathValue("room")
	var by *store.Participant
	if sess != nil {
		by = sess.p
	}
	c, err := s.bus.Store.SetDocumentDeleted(s.roomAuditing(r, sess, action, room, nil), room, id, deleted, by)
	if s.docChangeFailed(w, err, "delete_document_failed") {
		return
	}
	s.bus.Notify(room)
	s.log.Info("document_deleted", zap.String("room", room), zap.Int64("document", c.Document.ID), zap.Bool("deleted", deleted))
	w.WriteHeader(http.StatusNoContent)
}

// deletedDocuments lists the room's deleted documents for its admins to restore (005-AC26).
func (s *Server) deletedDocuments(w http.ResponseWriter, r *http.Request, sess *session) {
	if !s.asRoomAdmin(w, r, sess) {
		return
	}
	docs, err := s.bus.Store.DeletedDocuments(r.Context(), r.PathValue("room"))
	if err != nil {
		s.serverError(w, "deleted_documents_failed", err)
		return
	}
	writeJSON(w, http.StatusOK, docs)
}

// documentText answers a text revision of a document as Markdown, the latest by default or ?rev=,
// for agents: the room shows it as HTML (012, read_document).
func (s *Server) documentText(w http.ResponseWriter, r *http.Request, sess session) {
	d, ok := s.document(w, r, sess)
	if !ok {
		return
	}
	n := d.Revisions
	if v := r.URL.Query().Get("rev"); v != "" {
		var err error
		if n, err = strconv.Atoi(v); err != nil || n < 1 {
			httpError(w, http.StatusBadRequest, "rev must be a revision number from 1")
			return
		}
	}
	if d.Revisions == 0 {
		httpError(w, http.StatusUnprocessableEntity, "this document has no text: it is a "+d.Format)
		return
	}
	rev, err := s.bus.Store.Revision(r.Context(), d.ID, n)
	if errors.Is(err, store.ErrNotFound) {
		httpError(w, http.StatusNotFound, fmt.Sprintf("no revision %d; the document has %d", n, d.Revisions))
		return
	}
	if err != nil {
		s.serverError(w, "document_text_failed", err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"document": d.ID, "name": d.Name, "revision": rev.N, "revisions": d.Revisions,
		"author": rev.Author, "created_at": rev.CreatedAt, "text": rev.Body})
}
